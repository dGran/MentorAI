const [MAIN_Q, MAIN_C, RAMA_Q, RAMA_C, ...PERMITIDOS_Q] = process.argv.slice(2);
const carga = (f, g) => { const w = {}; global.window = w; delete require.cache[require.resolve(f)]; require(f); return w[g]; };
const planas = (datos) => Object.entries(datos).flatMap(([k, v]) => (v.questions ?? v).map((q) => ({ k, ...q })));
const antes = [...planas(carga(MAIN_Q, "MENTORAI_QUIZZES")), ...planas(carga(MAIN_C, "MENTORAI_CHECKS"))];
const despues = [...planas(carga(RAMA_Q, "MENTORAI_QUIZZES")), ...planas(carga(RAMA_C, "MENTORAI_CHECKS"))];
const problemas = [];
if (antes.map((q) => q.k + q.id).join() !== despues.map((q) => q.k + q.id).join()) problemas.push("ids u orden distintos");
let opcionesCambiadas = 0, explicaciones = 0, enunciados = [];
antes.forEach((q, i) => { const d = despues[i]; if (!d) return;
  if (d.a !== q.a) problemas.push(`a cambia en ${q.id}`);
  if (d.o.length !== q.o.length) problemas.push(`número de opciones cambia en ${q.id}`);
  if (d.q !== q.q) (PERMITIDOS_Q.includes(q.id) ? enunciados.push(q.id) : problemas.push(`q cambia en ${q.id}`));
  if (JSON.stringify(d.o) !== JSON.stringify(q.o)) opcionesCambiadas++;
  if (d.w !== q.w) explicaciones++; });
console.log(`preguntas ${antes.length} · con opciones reescritas ${opcionesCambiadas} · w cambiados ${explicaciones} · q cambiados (permitidos) ${enunciados.join(",") || 0} · problemas ${problemas.length ? problemas.join("; ") : 0}`);
process.exit(problemas.length ? 1 : 0);
