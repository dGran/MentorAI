const { abrir } = require("./cdp.js");
const [BASE] = process.argv.slice(2);
(async () => { const b = await abrir(9427); await b.ancho(1280, 900, false); const L = `${BASE}/tutorials/git-ramas-y-flujo.html`;
  await b.ir(L, 800); await b.evaluar(`localStorage.setItem("academia-progress", JSON.stringify(["git-ramas-y-flujo"])); 1`); await b.ir(L, 1000);
  await b.evaluar(`document.querySelector(".tutorial-action--reset").click(); 1`); await b.sleep(300);
  const r = await b.evaluar(`(() => { const r = document.querySelector(".undo-toast").getBoundingClientRect(); return { x: r.left + r.width / 2, y: r.top + r.height / 2 }; })()`);
  await b.send("Input.dispatchMouseEvent", { type: "mouseMoved", x: r.x, y: r.y }); await b.sleep(9000);
  console.log("hover 9 s → abierto:", await b.evaluar(`document.querySelector(".undo-toast").classList.contains("is-open")`));
  await b.send("Input.dispatchMouseEvent", { type: "mouseMoved", x: 5, y: 5 }); await b.sleep(8500);
  console.log("8,5 s tras salir → abierto:", await b.evaluar(`document.querySelector(".undo-toast").classList.contains("is-open")`));
  b.cerrar(); })();
